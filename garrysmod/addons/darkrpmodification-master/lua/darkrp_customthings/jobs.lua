local function AddWeaponsToJobs(teamList, weaponsToGive)
    for _, teamId in ipairs(teamList) do
        local jobData = RPExtraTeams and RPExtraTeams[teamId]
        if jobData then
            jobData.weapons = jobData.weapons or {}
            for _, weaponClass in ipairs(weaponsToGive) do
                if not table.HasValue(jobData.weapons, weaponClass) then
                    table.insert(jobData.weapons, weaponClass)
                end
            end
        end
    end
end

