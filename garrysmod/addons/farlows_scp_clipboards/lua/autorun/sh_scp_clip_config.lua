--========================================================--
--   DARKRP CLEARANCE LOADING (Option B — autorun safe)
--========================================================--

hook.Add("loadCustomDarkRPItems", "LoadSCPClipboardConfig", function()

    -- Delay ensures TEAM_ enums exist
    timer.Simple(0, function()

        print("[SCP] Loading clipboard clearance configuration...")

        --========================================--
        --   CLEARANCE LEVELS BY TEAM
        --========================================--
        SCP_Clearance = {
            [TEAM_DCLASS]      = 0,
            [TEAM_APPRES]      = 1,
            [TEAM_JRRES]       = 2,
            [TEAM_RES]         = 3,
            [TEAM_PSYCHRES]    = 4,
            [TEAM_DOR]    = 6,
            [TEAM_REI]    = 6,
        }

        print("[SCP DEBUG] Clearance table loaded")

        --========================================--
        --   FUNCTION: GetPlayerClearance
        --========================================--
        function GetPlayerClearance(ply)
            if not IsValid(ply) then return 0 end
            return SCP_Clearance[ply:Team()] or 0
        end

        print("[SCP DEBUG] GetPlayerClearance defined")

        --========================================--
        --   HOOK: Update clearance on job change
        --========================================--
        hook.Add("OnPlayerChangedTeam", "SCP_UpdateClearance", function(ply)
            local new = GetPlayerClearance(ply)
            ply:SetNWInt("SCP_Clearance", new)
            ply:ChatPrint("[SCP] Your clearance level is now: Level " .. new)
        end)

        --========================================--
        --   INITIALIZE CLEARANCE ON SPAWN
        --========================================--
        hook.Add("PlayerInitialSpawn", "SCP_InitClearance", function(ply)
            timer.Simple(1, function()
                if not IsValid(ply) then return end
                ply:SetNWInt("SCP_Clearance", GetPlayerClearance(ply))
            end)
        end)

    end)

end)